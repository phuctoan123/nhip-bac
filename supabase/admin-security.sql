-- Giai đoạn 2-3: nhật ký đăng nhập và rate limit booking.
-- Chạy sau services-reviews.sql trong Supabase SQL Editor.

create table if not exists public.admin_login_attempts (
  id bigint generated by default as identity primary key,
  ip_hash text not null,
  attempted_at timestamptz not null default now()
);

create index if not exists admin_login_attempts_ip_time_idx
  on public.admin_login_attempts (ip_hash, attempted_at desc);

alter table public.admin_login_attempts enable row level security;

create table if not exists public.booking_rate_log (
  id bigint generated by default as identity primary key,
  ip_hash text not null,
  phone_hash text not null,
  created_at timestamptz not null default now()
);

create index if not exists booking_rate_log_ip_time_idx
  on public.booking_rate_log (ip_hash, created_at desc);

create index if not exists booking_rate_log_phone_time_idx
  on public.booking_rate_log (phone_hash, created_at desc);

alter table public.booking_rate_log enable row level security;
